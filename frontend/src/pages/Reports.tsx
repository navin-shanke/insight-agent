import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { FileText, ArrowRight, Calendar, Search, ExternalLink } from 'lucide-react';
import { SkeletonCard } from '../design-system/components/SkeletonCard';
import { EmptyState } from '../design-system/components/EmptyState';
import { fetchReports } from '../api/reports';
import { Report } from '../types';

export const Reports: React.FC = () => {
  const navigate = useNavigate();
  const [reports, setReports] = useState<Report[]>([]);
  const [loading, setLoading] = useState(true);
  const [searchTerm, setSearchTerm] = useState('');

  const loadData = async () => {
    setLoading(true);
    try {
      const res = await fetchReports({ q: searchTerm.trim() || undefined });
      setReports(res.items || []);
    } catch {
      // ignore
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  return (
    <div className="space-y-6 animate-fade-in">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-2 border-b border-[#1E2535]">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <FileText className="w-5 h-5 text-indigo-400" />
            <h1 className="text-2xl font-bold tracking-tight text-slate-100">
              Research Reports Library
            </h1>
          </div>
          <p className="text-xs text-slate-400">
            Source-grounded comprehensive synthesis generated by completed investigations.
          </p>
        </div>

        <form
          onSubmit={(e) => {
            e.preventDefault();
            loadData();
          }}
          className="relative"
        >
          <Search className="w-3.5 h-3.5 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
          <input
            type="text"
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            placeholder="Search reports..."
            className="bg-[#11151E] border border-[#1E2535] rounded-lg pl-9 pr-3 py-1.5 text-xs text-slate-200 placeholder:text-slate-400 focus:outline-none focus:border-indigo-500/50"
          />
        </form>
      </div>

      {loading ? (
        <div className="space-y-3">
          <SkeletonCard rows={2} />
          <SkeletonCard rows={2} />
        </div>
      ) : reports.length > 0 ? (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {reports.map((report) => (
            <div
              key={report.id}
              onClick={() => navigate(`/reports/${report.id}`)}
              className="bg-[#11151E] border border-[#1E2535] rounded-xl p-5 hover:border-indigo-500/40 hover:shadow-lg hover:shadow-black/20 cursor-pointer transition-all flex flex-col justify-between space-y-4 group"
            >
              <div className="space-y-2">
                <div className="flex items-center justify-between text-[11px] text-slate-400 font-mono">
                  <span>{new Date(report.created_at).toLocaleDateString()}</span>
                  <span className="text-indigo-400 font-semibold">{report.discovery_ids?.length || 0} discoveries</span>
                </div>
                <h3 className="text-sm font-semibold text-slate-100 group-hover:text-indigo-300 transition-colors line-clamp-2 leading-snug">
                  {report.title}
                </h3>
                {report.summary && (
                  <p className="text-xs text-slate-400 line-clamp-3 leading-relaxed">
                    {report.summary}
                  </p>
                )}
              </div>

              <div className="pt-3 border-t border-[#1E2535] flex items-center justify-between text-xs font-medium text-indigo-400 group-hover:text-indigo-300 transition-colors">
                <span>Read Full Report</span>
                <ArrowRight className="w-3.5 h-3.5 group-hover:translate-x-0.5 transition-transform" />
              </div>
            </div>
          ))}
        </div>
      ) : (
        <EmptyState
          icon={FileText}
          title="No Reports Generated Yet"
          description="Reports are authored automatically once autonomous research loops finish synthesizing their findings."
        />
      )}
    </div>
  );
};
